#include "../src/ast.h"
#include "../src/codegen.h"
#include "../src/parser.h"
#include "../src/return.h"
#include "../src/scanner.h"
#include "../src/semantic.h"
#include <stdio.h>

int main(int argc, char **argv) {
  if (argc < 2) {
    (void)fprintf(stderr, "Usage: %s <source file>\n", argv[0]);
    return ERR_INTERNAL;
  }

  FILE *src = fopen(argv[1], "r");
  if (src == NULL) {
    (void)fprintf(stderr, "Couldn't open source file.\n");
    return ERR_INTERNAL;
  }

  Scanner sc = scanner_init(src);
  ASTNode *program = NULL;

  // on an error the parser frees the AST itself, only its code goes up
  ReturnCodes rc = parse_input(&sc, &program);
  if (rc == RETURN_SUCCESS) {
    rc = semantic_analysis(program);
    // the code is generated only from a semantically correct AST
    if (rc == RETURN_SUCCESS) {
      rc = generate_code(program, stdout);
    }
    // neither the semantic analysis nor the generator frees the AST
    ast_free(program);
  }

  (void)fclose(src);
  return rc;
}
